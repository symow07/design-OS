def drawn_as(shape_id: str) -> tuple:
    """(form, variant, closure) — how a catalogue shape is drawn."""
    shape = next(s for s in SHAPES if s["id"] == shape_id)
    return shape["form"], shape["variant"], shape["closure"]


def typical_size(shape: dict) -> dict:
    """The middle of a shape's typical ranges, in millimetres — ``{"height_mm", "width_mm", "depth_mm"}``."""
    return {"%s_mm" % k: round(sum(v) / 2.0, 1) for k, v in shape["size_mm"].items()}
